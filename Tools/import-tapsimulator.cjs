// Rebuild the MIT-licensed game modules from a pinned upstream release.
// Usage: node Tools/import-tapsimulator.cjs [downloaded-source.lua downloaded-LICENSE]
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const revision = '11e1ab4ac99cb8a94e2b1146b9983cf2a4d3c478';
const upstream = 'https://raw.githubusercontent.com/TrustyCoding/slopix-hub/' + revision + '/';
const output = path.resolve(__dirname, '../Games/TapSimulator');
const features = [
  'home', 'performance', 'tap', 'upgrades', 'skilltree', 'hatch', 'pets', 'treats',
  'enchant', 'shrine', 'tradepost', 'craft', 'honeypot', 'potions', 'rewards',
  'stars', 'items', 'pickups', 'dig', 'creatures', 'defense', 'minigames',
  'mining', 'fishing', 'halloween', 'dungeon',
].map(name => 'features/' + name);
const names = ['shared/env', 'shared/life', 'shared/home', 'shared/performance', 'core/env', ...features];

async function read(file, url) {
  if (file) return fs.readFileSync(file, 'utf8');
  const response = await fetch(url);
  if (!response.ok) throw new Error('Download failed: ' + response.status + ' ' + url);
  return response.text();
}

async function main() {
  const [source, license] = await Promise.all([
    read(process.argv[2], upstream + 'games/72858262610964.lua'),
    read(process.argv[3], upstream + 'LICENSE'),
  ]);
  if (!license.startsWith('MIT License') || !license.includes('Copyright (c) 2026 TrustyCoding')) {
    throw new Error('Unexpected upstream license');
  }
  const markers = [...source.matchAll(/^__modules\["([^"]+)"\] = function\(use\)[^\n]*\n/gm)];
  const modules = new Map();
  for (let index = 0; index < markers.length; index++) {
    const marker = markers[index];
    const finish = index + 1 < markers.length ? markers[index + 1].index : source.lastIndexOf('return use("main")');
    const body = source.slice(marker.index + marker[0].length, finish);
    if (!/\r?\nend\s*$/.test(body)) throw new Error('Invalid module boundary: ' + marker[1]);
    modules.set(marker[1], body.replace(/\r?\nend\s*$/, ''));
  }
  const factories = [];
  for (const name of names) {
    let body = modules.get(name);
    if (!body) throw new Error('Missing upstream module: ' + name);
    body = body.replaceAll('SlopixHub/TapSimulator', 'Abysall/TapSimulator')
      .replaceAll('"SlopixHub"', '"Abysall"')
      .replaceAll('"Slopix Hub"', '"Abysall Hub"')
      .replaceAll('https://discord.com/invite/WdPcxf5B83', 'https://dsc.gg/abysallhub')
      .replaceAll('__Slopix', '__AbysallTapSimulator');
    factories.push('Modules[' + JSON.stringify(name) + '] = function(use)\n' + body.trimEnd() + '\nend\n');
  }
  const header = '-- Generated by Tools/import-tapsimulator.cjs. Edit adapters in Main/Bridge.\n'
    + '-- Upstream: TrustyCoding/slopix-hub @ ' + revision + '\n--[[\n' + license.trim() + '\n]]\n';
  fs.mkdirSync(output, { recursive: true });
  fs.writeFileSync(path.join(output, 'Modules.luau'), header + 'local Modules = {}\n\n' + factories.join('\n')
    + '\nreturn { Factories = Modules, Features = {\n'
    + features.map(name => '    ' + JSON.stringify(name) + ',').join('\n') + '\n} }\n');
  fs.writeFileSync(path.join(output, 'LICENSE.slopix.txt'), license.trim() + '\n');
  fs.writeFileSync(path.join(output, 'upstream.json'), JSON.stringify({
    repository: 'https://github.com/TrustyCoding/slopix-hub', revision,
    source: 'games/72858262610964.lua',
    sha256: crypto.createHash('sha256').update(source).digest('hex'),
    license: 'MIT', modules: names,
    adaptations: ['Abysall file paths and persistent globals', 'Native Abysall UI and startup adapters; upstream UI/assets/settings are excluded'],
  }, null, 2) + '\n');
  console.log('Imported ' + features.length + ' feature modules (' + names.length + ' factories) from ' + revision);
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
